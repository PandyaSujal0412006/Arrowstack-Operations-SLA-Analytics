import os
import random
import datetime
import sqlite3
import pandas as pd
import numpy as np

# Set fixed seed for reproducibility
np.random.seed(42)
random.seed(42)

DATA_DIR = os.path.dirname(os.path.abspath(__file__))
RAW_CSV_PATH = os.path.join(DATA_DIR, "raw_tickets_data.csv")
CLEAN_CSV_PATH = os.path.join(DATA_DIR, "cleaned_tickets_data.csv")
DB_PATH = os.path.join(DATA_DIR, "operations_database.db")

PRIORITIES = {
    "P1 - Critical": {"sla_hours": 4.0, "weight": 0.12},
    "P2 - High": {"sla_hours": 12.0, "weight": 0.28},
    "P3 - Medium": {"sla_hours": 48.0, "weight": 0.42},
    "P4 - Low": {"sla_hours": 96.0, "weight": 0.18}
}

CATEGORIES = [
    "Cloud Infrastructure & Outage",
    "Access & Identity Management",
    "Billing & Invoicing Query",
    "Software Bug / Defect",
    "Hardware & Edge Failure"
]

TEAMS = {
    "DevOps & SRE": ["Agent-DevOps-1", "Agent-DevOps-2", "Agent-DevOps-3"],
    "Tier 1 Support": ["Agent-T1-1", "Agent-T1-2", "Agent-T1-3", "Agent-T1-4"],
    "Tier 2 Engineering": ["Agent-T2-1", "Agent-T2-2", "Agent-T2-3"],
    "FinOps & Billing": ["Agent-Fin-1", "Agent-Fin-2"],
    "Security & SecOps": ["Agent-Sec-1", "Agent-Sec-2"]
}

CATEGORY_TEAM_MAP = {
    "Cloud Infrastructure & Outage": "DevOps & SRE",
    "Access & Identity Management": "Security & SecOps",
    "Billing & Invoicing Query": "FinOps & Billing",
    "Software Bug / Defect": "Tier 2 Engineering",
    "Hardware & Edge Failure": "Tier 1 Support"
}

CUSTOMER_TIERS = ["Enterprise Platinum", "Enterprise Gold", "Standard Business"]

ROOT_CAUSES = [
    "Staffing Deficit / Peak Queue Surge",
    "Third-Party / Cloud Vendor Dependency",
    "Incomplete Customer Diagnostics",
    "Complex Code Defect / Regression",
    "Cross-Team Escalation Latency"
]

def generate_ticket_records(num_tickets=4200):
    start_time = datetime.datetime(2025, 1, 1, 8, 0, 0)
    end_time = datetime.datetime(2026, 10, 25, 18, 0, 0)
    total_seconds = int((end_time - start_time).total_seconds())

    records = []
    
    priority_names = list(PRIORITIES.keys())
    priority_weights = [PRIORITIES[p]["weight"] for p in priority_names]

    for idx in range(1, num_tickets + 1):
        ticket_id = f"TCK-202526-{idx:05d}"
        
        # Random creation timestamp
        rand_sec = random.randint(0, total_seconds)
        created_at = start_time + datetime.timedelta(seconds=rand_sec)
        
        priority = random.choices(priority_names, weights=priority_weights, k=1)[0]
        sla_target = PRIORITIES[priority]["sla_hours"]
        
        category = random.choices(
            CATEGORIES,
            weights=[0.24, 0.20, 0.18, 0.26, 0.12],
            k=1
        )[0]
        
        # Determine assigned team based on category with 10% cross-routing
        if random.random() < 0.90:
            assigned_team = CATEGORY_TEAM_MAP[category]
        else:
            assigned_team = random.choice(list(TEAMS.keys()))
            
        assigned_agent = random.choice(TEAMS[assigned_team])
        cust_tier = random.choices(CUSTOMER_TIERS, weights=[0.45, 0.35, 0.20], k=1)[0]
        
        # Determine ticket status
        # Recent tickets have higher probability of being open
        age_in_days = (end_time - created_at).days
        if age_in_days < 7 and random.random() < 0.40:
            status = random.choice(["Open", "In Progress", "Escalated"])
        elif age_in_days < 30 and random.random() < 0.12:
            status = random.choice(["Open", "In Progress"])
        elif random.random() < 0.04:
            status = "In Progress"
        else:
            status = random.choice(["Resolved", "Closed"])

        if status in ["Resolved", "Closed"]:
            # Realistic log-normal resolution distribution
            # ~82% compliant, ~18% breach
            is_breach = (random.random() < 0.17)
            if is_breach:
                # Actual hours exceeds SLA target by 1.1x to 3.5x
                actual_res_hours = round(sla_target * random.uniform(1.15, 3.2), 2)
                sla_status = "Breached"
                root_cause = random.choice(ROOT_CAUSES)
                csat = random.choices([1, 2, 3, 4], weights=[0.25, 0.35, 0.25, 0.15], k=1)[0]
            else:
                # Completed within SLA target (0.15x to 0.95x of SLA target)
                actual_res_hours = round(sla_target * random.uniform(0.12, 0.94), 2)
                sla_status = "Compliant"
                root_cause = "N/A - SLA Met"
                csat = random.choices([3, 4, 5], weights=[0.10, 0.45, 0.45], k=1)[0]
                
            resolved_at = created_at + datetime.timedelta(hours=actual_res_hours)
        else:
            actual_res_hours = None
            resolved_at = None
            elapsed_hours = (end_time - created_at).total_seconds() / 3600.0
            if elapsed_hours > sla_target:
                sla_status = "Breached (Open)"
                root_cause = "Queue Backlog / In-Flight Breach"
            else:
                sla_status = "In Progress (Within SLA)"
                root_cause = "Pending Resolution"
            csat = None

        records.append({
            "ticket_id": ticket_id,
            "created_at": created_at.strftime("%Y-%m-%d %H:%M:%S"),
            "resolved_at": resolved_at.strftime("%Y-%m-%d %H:%M:%S") if resolved_at else None,
            "ticket_status": status,
            "priority": priority,
            "category": category,
            "assigned_team": assigned_team,
            "assigned_agent": assigned_agent,
            "customer_tier": cust_tier,
            "sla_target_hours": sla_target,
            "actual_resolution_hours": actual_res_hours,
            "sla_status": sla_status,
            "breach_root_cause": root_cause,
            "csat_score": csat
        })

    return pd.DataFrame(records)

def create_sqlite_database(tickets_df):
    if os.path.exists(DB_PATH):
        os.remove(DB_PATH)
        
    conn = sqlite3.connect(DB_PATH)
    cursor = conn.cursor()
    
    # 1. Fact Tickets Table
    tickets_df.to_sql("fact_tickets", conn, if_exists="replace", index=False)
    
    # 2. Dim SLA Policies
    sla_data = [
        {"priority": p, "sla_target_hours": d["sla_hours"], "target_compliance_pct": 95.0}
        for p, d in PRIORITIES.items()
    ]
    pd.DataFrame(sla_data).to_sql("dim_sla_policies", conn, if_exists="replace", index=False)
    
    # 3. Dim Teams & Agents
    agent_rows = []
    for team, agents in TEAMS.items():
        for ag in agents:
            agent_rows.append({"agent_name": ag, "team_name": team})
    pd.DataFrame(agent_rows).to_sql("dim_agents", conn, if_exists="replace", index=False)
    
    # Indexes
    cursor.execute("CREATE INDEX IF NOT EXISTS idx_ticket_created ON fact_tickets(created_at);")
    cursor.execute("CREATE INDEX IF NOT EXISTS idx_ticket_status ON fact_tickets(ticket_status);")
    cursor.execute("CREATE INDEX IF NOT EXISTS idx_ticket_priority ON fact_tickets(priority);")
    cursor.execute("CREATE INDEX IF NOT EXISTS idx_ticket_team ON fact_tickets(assigned_team);")
    cursor.execute("CREATE INDEX IF NOT EXISTS idx_ticket_sla ON fact_tickets(sla_status);")
    
    # Analytical View: Team SLA Performance Summary
    cursor.execute("""
    CREATE VIEW IF NOT EXISTS v_team_sla_summary AS
    SELECT 
        assigned_team,
        COUNT(ticket_id) AS total_tickets,
        SUM(CASE WHEN is_resolved = 1 THEN 1 ELSE 0 END) AS resolved_tickets,
        SUM(CASE WHEN is_resolved = 0 THEN 1 ELSE 0 END) AS open_tickets,
        SUM(CASE WHEN is_resolved = 1 AND sla_status = 'Compliant' THEN 1 ELSE 0 END) AS compliant_tickets,
        SUM(CASE WHEN is_resolved = 1 AND sla_status = 'Breached' THEN 1 ELSE 0 END) AS breached_tickets,
        ROUND(
            SUM(CASE WHEN is_resolved = 1 AND sla_status = 'Compliant' THEN 1 ELSE 0 END) * 100.0 / 
            NULLIF(SUM(CASE WHEN is_resolved = 1 THEN 1 ELSE 0 END), 0),
            2
        ) AS sla_compliance_pct,
        ROUND(AVG(CASE WHEN is_resolved = 1 THEN actual_resolution_hours ELSE NULL END), 2) AS mttr_hours,
        ROUND(AVG(csat_score), 2) AS avg_csat_score
    FROM fact_tickets
    GROUP BY assigned_team;
    """)
    
    conn.commit()
    
    conn.commit()
    conn.close()
    print(f"[OK] SQLite Operations Database initialized at {DB_PATH}")

def main():
    print("Generating synthetic enterprise operations & SLA ticketing dataset...")
    raw_df = generate_ticket_records(num_tickets=4200)
    raw_df.to_csv(RAW_CSV_PATH, index=False)
    print(f"[OK] Raw tickets dataset saved ({len(raw_df)} rows) to {RAW_CSV_PATH}")
    
    # Transformation and feature enrichment
    clean_df = raw_df.copy()
    clean_df["created_date"] = pd.to_datetime(clean_df["created_at"]).dt.date
    clean_df["created_year_month"] = pd.to_datetime(clean_df["created_at"]).dt.strftime("%Y-%m")
    clean_df["is_resolved"] = clean_df["ticket_status"].isin(["Resolved", "Closed"]).astype(int)
    clean_df["is_breached"] = clean_df["sla_status"].str.contains("Breached").astype(int)
    
    clean_df.to_csv(CLEAN_CSV_PATH, index=False)
    print(f"[OK] Cleaned tickets dataset saved to {CLEAN_CSV_PATH}")
    
    print("Creating relational SQLite database...")
    create_sqlite_database(clean_df)
    
    resolved_subset = clean_df[clean_df["is_resolved"] == 1]
    sla_compliance = (resolved_subset["sla_status"] == "Compliant").sum() / len(resolved_subset) * 100.0
    mttr = resolved_subset["actual_resolution_hours"].mean()
    
    print("\n--- SYNTHETIC OPERATIONS DATA SUMMARY ---")
    print(f"Total Tickets: {len(clean_df):,}")
    print(f"Resolved Tickets: {len(resolved_subset):,} ({len(resolved_subset)/len(clean_df)*100:.1f}%)")
    print(f"Open / In Progress: {len(clean_df) - len(resolved_subset):,}")
    print(f"SLA Compliance Rate (Resolved): {sla_compliance:.2f}%")
    print(f"SLA Breach Rate (Resolved): {100.0 - sla_compliance:.2f}%")
    print(f"Mean Time To Resolve (MTTR): {mttr:.2f} hours")
    print("------------------------------------------\n")

if __name__ == "__main__":
    main()
